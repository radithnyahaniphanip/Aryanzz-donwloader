import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read=path=>readFileSync(new URL(path,import.meta.url),"utf8");
const html=read("../public/index.html");
const game=read("../public/eclipse-rpg.js");
const css=read("../public/eclipse-rpg.css");
const sw=read("../public/sw.js");
const manifest=JSON.parse(read("../public/workspace-manifest.json"));
const pkg=JSON.parse(read("../package.json"));
const counts=[...game.matchAll(/count:(\d+),mult:/g)].map(m=>Number(m[1]));
assert.equal(counts.reduce((a,b)=>a+b,0),247,"equipment rarity counts must total 247");
assert.match(game,/length:600/,"game must generate 600 skills");
assert.match(game,/length:900/,"game must generate 900 bosses");
assert.match(game,/BOSS_HP=\[100,300,500,800,1200\]/,"first boss HP milestones must match the design");
assert.match(game,/function nextReset\(period\)/,"daily, weekly and monthly reset timers must exist");
assert.match(game,/function updateQuest\(type,amount\)/,"quest progress must update from game actions");
assert.match(game,/function hitTarget\(target,raw,kind\)/,"combat damage must be implemented");
assert.match(game,/function upgradeItem\(id\)/,"equipment upgrades must be implemented");
assert.match(game,/function chooseRune\(n\)/,"rune puzzle interaction must be implemented");
assert.match(game,/localStorage\.setItem\(SAVE_KEY/,"game save must persist locally");
assert.match(html,/data-panel="eclipseRpg"/,"game must be discoverable in the Tools hub");
assert.match(html,/id="eclipseRpg"/,"game panel must be mounted inside the workspace");
assert.match(html,/\/eclipse-rpg\.js\?v=__ARYANZZ_VERSION__/,"game script must be versioned");
assert.match(html,/\/eclipse-rpg\.css\?v=__ARYANZZ_VERSION__/,"game stylesheet must be versioned");
assert.ok(sw.includes("/eclipse-rpg.js?v=__ARYANZZ_VERSION__")&&sw.includes("/eclipse-rpg.css?v=__ARYANZZ_VERSION__"),"PWA shell must cache the game assets");
assert.ok(manifest.featureModules.some(m=>m.root==="#eclipseRpg"),"workspace ownership manifest must register the game module");
assert.ok(pkg.scripts["test:release"].includes("eclipse-rpg-smoke.mjs"),"release test command must run the RPG smoke test");
assert.ok(css.includes("@media(max-width:600px)")&&css.includes(".ecl-touch-controls"),"game UI must support mobile touch controls");
console.log("Eclipse RPG smoke checks passed: 247 equipment, 600 skills, 900 bosses, quest timers, combat, save and mobile UI.");
