import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
const html = read("../public/index.html");
const layout = read("../public/workspace-layout.js");
const navigation = read("../public/workspace-navigation.js");
const quote = read("../public/wa-quote-generator.js");
const sw = read("../public/sw.js");
assert.ok(html.includes('id="waQuoteTools"'), "WA Quote panel exists");
assert.ok(layout.includes("const waQuotePanel=$('waQuoteTools')"), "layout controller owns WA Quote panel");
assert.ok(layout.includes("toolsArea.insertBefore(waQuotePanel,profilePanel||null)"), "WA Quote is moved into the tools workspace before navigation initializes");
assert.ok(navigation.includes("candidate.parentElement!==toolsArea"), "navigation requires every tool panel to be a direct child");
assert.ok(html.indexOf('/workspace-layout.js?v=__ARYANZZ_VERSION__') < html.indexOf('/workspace-navigation.js?v=__ARYANZZ_VERSION__'), "layout normalization runs before navigation");
assert.ok(html.includes('data-panel="waQuoteTools"'), "WA Quote launcher targets the panel id");
assert.ok(quote.includes("e.composedPath?.()") && quote.includes("},true);"), "WA Quote uses capture-phase delegated click handling");
for (const id of ["waqAdd","waqGenerate","waqDownload","waqCopy","waqReset","waqBack"]) assert.ok(quote.includes('closest("#'+id+'")'), "WA Quote action is wired: "+id);
assert.ok(quote.includes('state.style==="clean"'), "Clean style selection changes the rendered output");
assert.ok(quote.includes('state.device==="iphone"?185:165'), "iPhone selection changes the rendered layout");
assert.ok(sw.includes("/wa-quote-generator.js?v=__ARYANZZ_VERSION__"), "WA Quote controller remains precached");
console.log("WA Quote navigation smoke test passed: panel ownership, button delegation, style and device state.");
