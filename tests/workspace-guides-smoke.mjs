import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
const html = read("../public/index.html");
const guides = read("../public/workspace-guides.js");
const css = read("../public/workspace-guides.css");
const sw = read("../public/sw.js");
const manifest = JSON.parse(read("../public/workspace-manifest.json"));
const expected = ["speed","checker","linkBypass","heart","members","mediaStudio","queue","editor","musicFinder","audioStudio","history","waQuoteTools","imageTools","pdfTools","qrTools","securityTools","gradientStudio","fileHash","colorStudio","profile","owner"];
assert.ok(html.includes('/workspace-guides.css?v=__ARYANZZ_VERSION__'), "guide stylesheet is linked");
assert.ok(html.includes('/workspace-guides.js?v=__ARYANZZ_VERSION__'), "guide controller is linked");
assert.ok(html.includes('data-guide-open="all"'), "guide hub entry is available in Tools");
assert.ok(sw.includes('/workspace-guides.css?v=__ARYANZZ_VERSION__') && sw.includes('/workspace-guides.js?v=__ARYANZZ_VERSION__'), "service worker precaches guide assets");
assert.ok(guides.includes("localStorage") && guides.includes("Tandai sudah dipelajari") && guides.includes("Buka fitur"), "guide progress and feature navigation are functional");
for (const id of expected) assert.ok(guides.includes('id:"'+id+'"'), "missing feature guide: "+id);
assert.equal(expected.length, 21, "expected 21 feature guides");
assert.ok(guides.includes("Menunggu konfigurasi Cloudflare D1"), "inactive visitor module is honestly labeled");
assert.ok(guides.includes("bukan alat medis"), "camera experiment limitation is explicit");
assert.ok(guides.includes("tidak melewati CAPTCHA"), "link bypass limitation is explicit");
assert.ok(css.includes(".ary-guide-overlay") && css.includes("@media(max-width:760px)"), "responsive guide interface styles exist");
const module = manifest.featureModules.find(item => item.js?.includes("/workspace-guides.js"));
assert.ok(module && module.css.includes("/workspace-guides.css"), "guide module is registered in workspace manifest");
console.log("ARYANZZ workspace guides smoke test passed: 21 feature guides, navigation, progress, honest availability, responsive UI.");
